"""Write zora/generate/drop_square_table.py, Universal Drops v2.0' drop squares per screen type,
from the model in zora/generate/drop_squares.py (the floors, the door squares, the ladder and the push
block). tests/test_drop_squares.py keeps the written table equal to the model.

    python3 scripts/make_drop_square_table.py"""
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from zora.generate.drop_squares import model_drop_squares  # noqa: E402
from zora.generate.item_spots import FLOORS  # noqa: E402
from zora.model.rooms import PUSH_BLOCK_VARIANT  # noqa: E402

TABLE = REPO / "zora" / "generate" / "drop_square_table.py"
PER_LINE = 14
HEADER = '''"""Universal Drops v2.0: each screen type's drop squares ($XY), the model's table
(zora/generate/drop_squares.py). Generated by scripts/make_drop_square_table.py; do not edit by hand
(tests/test_drop_squares.py keeps it equal to the model). A screen type left out has none."""

DROP_SQUARES: dict[int, frozenset[int]] = {
'''


def table_source() -> str:
    lines = [HEADER]
    for layout_code in sorted({*FLOORS, *(layout | PUSH_BLOCK_VARIANT for layout in FLOORS)}):
        squares = sorted(model_drop_squares(layout_code))
        if not squares:
            continue
        codes = [f"0x{square:02X}" for square in squares]
        chunks = [", ".join(codes[i:i + PER_LINE]) for i in range(0, len(codes), PER_LINE)]
        body = (",\n" + " " * 8).join(chunks)
        lines.append(f"    0x{layout_code:02X}: frozenset({{\n        {body}}}),\n")
    lines.append("}\n")
    return "".join(lines)


def main() -> None:
    TABLE.write_text(table_source())
    sys.stdout.write(f"wrote {TABLE.relative_to(REPO)}\n")


if __name__ == "__main__":
    main()
