"""Universal Drops v2.0: the squares a room's item may stand on, from the room floors (ZORA's own
rule, beyond the spec; docs/zora-extras.md "Universal Drops v2.0", the model of
docs/reports/research-universal-drops-balance.md section 3.3).

A square ($XY, as item_spots and the level item position tables pack it) is a drop square of a screen
type when Link can collect an item there from every arrival the logic accepts:

- the floor is the room's as the game draws it (item_spots.FLOORS, 12 columns by 7 rows);
- Link comes in through a door onto its door squares: north and south the two middle squares of the
  top and bottom rows, west and east the middle row's end squares (checked in the emulator,
  tests/test_drop_squares_emulator.py);
- floor, sand and black squares are walkable; blocks, statues and stairs are not;
- water is crossed only with the ladder and one square at a time (checked in the emulator), and holds
  an item only in a ladder layout (acceptance_check.LADDER_LAYOUTS, VA-REJ-07 (iv)), where the logic
  gives the room's items the ladder;
- every set of sides the layout's arrival rule accepts (dungeon_walk.arrival_accepts, VA-REJ-17)
  holds a door that reaches the square.

A push-block screen type (layout + $40) takes its plain layout's squares minus its push block's square
and the four it can slide into. The push block is the game's (FindAndCreatePushBlockObject): the first
block in the middle row from the west wall, or the object alone at $D9 when that row has none; a push
moves it one square (checked in the emulator).

The narrow stair room ($1B) and Zelda's room ($27) keep T5's merged rows: their east (and Zelda's
north) door squares are stairs or blocks, so the model finds no square every arrival reaches; the
shape stage never opens the narrow stair room's east wall, and Zelda's room holds no item.

DROP_SQUARES (drop_square_table.py) is this model's table, generated by scripts/make_drop_square_table.py;
tests/test_drop_squares.py keeps the two equal."""
from __future__ import annotations

from collections import deque
from collections.abc import Iterable
from itertools import combinations

from ..model.enums import Enemy, Item, RoomType, Side
from ..model.levels import Level
from ..model.rooms import LAYOUT_ID_MASK, PUSH_BLOCK_VARIANT
from .acceptance_check import LADDER_LAYOUTS
from .drop_square_table import DROP_SQUARES
from .dungeon_walk import arrival_accepts
from .errors import GenerationFailure
from .item_spots import FLOORS
from .shapes.t5_positions import t5_row

ROWS, COLUMNS = 7, 12
FIRST_COLUMN, FIRST_ROW = 0x2, 0x6            # the play area's top-left square, $26
WALKABLE = frozenset(".:_")                   # floor, sand, black
WATER = "~"
BLOCK = "B"
# Each door's squares (row, column): the floor squares next to its doorway
DOOR_SQUARES: dict[Side, tuple[tuple[int, int], ...]] = {
    Side.NORTH: ((0, 5), (0, 6)), Side.SOUTH: ((6, 5), (6, 6)),
    Side.WEST: ((3, 0),), Side.EAST: ((3, 11),)}
MIDDLE_ROW = 3                                # Y $9, the row the game searches for the push block
PUSH_BLOCK_FALLBACK = 0xD9                    # FindAndCreatePushBlockObject with no block in that row
ONE_COLUMN, ONE_ROW = 0x10, 0x01
# Layouts whose door squares are stairs or blocks, so the model leaves them no square: T5's rows instead
T5_ROW_LAYOUTS = frozenset({RoomType.NARROW_STAIR_ROOM, RoomType.ZELDA_ROOM})
DROP_SQUARE_FAILURE = "drop squares: a room item on a square its screen type does not allow"


def square_code(row: int, column: int) -> int:
    """The $XY of FLOORS' (row, column)."""
    return (column + FIRST_COLUMN) << 4 | (row + FIRST_ROW)


def reachable(floor: tuple[str, ...], starts: Iterable[tuple[int, int]], ladder: bool) -> set[tuple[int, int]]:
    """The squares Link can stand on from `starts`: walkable squares, and with the ladder one water
    square at a time, crossed straight onto the floor beyond."""
    seen: set[tuple[int, int]] = set()
    queue: deque[tuple[int, int]] = deque()
    for row, column in starts:
        if floor[row][column] in WALKABLE:
            seen.add((row, column))
            queue.append((row, column))
    while queue:
        row, column = queue.popleft()
        for d_row, d_column in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            near = (row + d_row, column + d_column)
            if not (0 <= near[0] < ROWS and 0 <= near[1] < COLUMNS) or near in seen:
                continue
            kind = floor[near[0]][near[1]]
            if kind in WALKABLE:
                seen.add(near)
                queue.append(near)
            elif kind == WATER and ladder:
                seen.add(near)                # the ladder: stand on one water square ...
                beyond = (near[0] + d_row, near[1] + d_column)
                if (0 <= beyond[0] < ROWS and 0 <= beyond[1] < COLUMNS) and beyond not in seen \
                        and floor[beyond[0]][beyond[1]] in WALKABLE:
                    seen.add(beyond)          # ... and step off it, straight on, onto floor
                    queue.append(beyond)
    return seen


def accepted_arrivals(layout: int) -> list[frozenset[Side]]:
    """Every set of sides the layout's arrival rule accepts (VA-REJ-17)."""
    return [frozenset(sides) for count in range(1, len(Side) + 1) for sides in combinations(Side, count)
            if arrival_accepts(layout, True, set(sides))]


def plain_drop_squares(layout: int) -> frozenset[int]:
    """The model's squares for a plain layout (no push block)."""
    if layout in T5_ROW_LAYOUTS:
        return frozenset(t5_row(layout, True))
    floor = FLOORS.get(layout)
    if floor is None:
        return frozenset()
    ladder = layout in LADDER_LAYOUTS
    regions = {side: reachable(floor, starts, ladder) for side, starts in DOOR_SQUARES.items()}
    arrivals = accepted_arrivals(layout)
    squares = set()
    for row in range(ROWS):
        for column in range(COLUMNS):
            kind = floor[row][column]
            if kind not in WALKABLE and not (kind == WATER and ladder):
                continue
            reaching = {side for side, region in regions.items() if (row, column) in region}
            if reaching and all(arrival & reaching for arrival in arrivals):
                squares.add(square_code(row, column))
    return frozenset(squares)


def push_block_square(layout: int) -> int:
    """FindAndCreatePushBlockObject: the first block in the middle row from the west wall, else $D9."""
    middle = FLOORS[layout][MIDDLE_ROW]
    column = next((column for column in range(COLUMNS - 1) if middle[column] == BLOCK), None)
    return PUSH_BLOCK_FALLBACK if column is None else square_code(MIDDLE_ROW, column)


def model_drop_squares(layout_code: int) -> frozenset[int]:
    """The model's drop squares of a screen type (a layout, or its push-block variant)."""
    layout = layout_code & LAYOUT_ID_MASK
    squares = plain_drop_squares(layout)
    if layout_code & PUSH_BLOCK_VARIANT and layout in FLOORS:
        block = push_block_square(layout)
        squares -= {block, block - ONE_COLUMN, block + ONE_COLUMN, block - ONE_ROW, block + ONE_ROW}
    return squares


def drop_squares(layout_code: int) -> frozenset[int]:
    """The table's drop squares of a screen type (empty for a type with none)."""
    return DROP_SQUARES.get(layout_code, frozenset())


def is_drop_square(layout_code: int, square: int) -> bool:
    """`square` is one of the screen type's drop squares (the rule passes such as Add L4 Sword take)."""
    return square in drop_squares(layout_code)


def misplaced_drops(levels: list[Level]) -> list[tuple[Level, int]]:
    """Every level room (by number) holding an item at a square its screen type's drop squares leave out.
    Ganon's room is never one: the game drops the Triforce of Power at Ganon's ashes, not at the room's
    position (Ganon_ActivateRoomItem; steps/highlight_no_drop_rooms.is_ganon_room)."""
    return [(level, room.room_num) for level in levels for room in level.rooms
            if room.item not in (Item.NOTHING, Item.TRIFORCE_OF_POWER) and room.enemy != Enemy.THE_BEAST
            and level.item_position_table[room.item_position] not in drop_squares(room.layout_code)]


def check_drop_squares(levels: list[Level]) -> None:
    """The finished-world check (owner ruling 5, 2026-11-05; docs/reports/gatekeeper-lessons.md
    invariant 9): any room item off its screen type's drop squares restarts the attempt."""
    misplaced = misplaced_drops(levels)
    if misplaced:
        level, room_num = misplaced[0]
        raise GenerationFailure(f"{DROP_SQUARE_FAILURE} (level {level.level_num} room ${room_num:02X})")
