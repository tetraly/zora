"""Item and location IDs: the ones ruled out are never Archipelago items, and IDs a released world
used stay the same (a game generated by one world version is played with that version, but the
names and IDs should not move under players between versions)."""
import unittest

from ..names import ITEM_NAME_TO_ID, LOCATION_NAME_TO_ID

NOT_ARCHIPELAGO_ITEMS = ("Rupee", "5 Rupees", "Heart", "Fairy", "Map", "Compass", "Triforce", "Triforce of Power",
                         "Clock")
# As world 0.2.3 and 0.3.0 numbered them; the renamed items as world 0.5.0 numbered them
PINNED_ITEMS = {"Raft": 13, "Heart Container": 27, "Blue Potion": 32,
                "Sword Upgrade": 101, "Candle Upgrade": 102, "Arrow Upgrade": 103, "Ring Upgrade": 104,
                "Boomerang Upgrade": 105, "Bomb Upgrade": 106, "Boots Upgrade": 107,
                "Pegasus Boots": 108, "Magical Boots": 109}
# ID 779 was "Level 4 Room 05" until ZORA added Floor and Stairway (be3250a): the name moved, not the ID
PINNED_LOCATIONS = {"Level 4 Room 05 Floor": 779, "Level 4 Room 05 Stairway": 780}


class TestIds(unittest.TestCase):
    def test_ruled_out_items_are_not_archipelago_items(self) -> None:
        for name in NOT_ARCHIPELAGO_ITEMS:
            self.assertNotIn(name, ITEM_NAME_TO_ID)

    def test_ids_unchanged(self) -> None:
        self.assertEqual({name: ITEM_NAME_TO_ID[name] for name in PINNED_ITEMS}, PINNED_ITEMS)
        self.assertEqual({name: LOCATION_NAME_TO_ID[name] for name in PINNED_LOCATIONS}, PINNED_LOCATIONS)

    def test_ids_are_unique(self) -> None:
        self.assertEqual(len(set(ITEM_NAME_TO_ID.values())), len(ITEM_NAME_TO_ID))
        self.assertEqual(len(set(LOCATION_NAME_TO_ID.values())), len(LOCATION_NAME_TO_ID))
